function generateSuitCards(suitKey, suitName, element, cards) {
  return cards.map((card, index) => ({
    id: `${suitKey}-${card.number}`,
    name: card.name,
    number: card.number,
    arcana: "minor",
    suit: suitName,
    element: element,
    image: getMinorArcanaImage(suitKey, card.number),
    keywords: card.keywords,
    upright: card.upright,
    reversed: card.reversed || card.upright,
    description: `${card.name} represents ${card.keywords.join(", ")} in the realm of ${suitName}.`
  }));
}

