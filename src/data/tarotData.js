export const fullDeck = [...majorArcana, ...minorArcana];

export function getCardById(id) {
  return fullDeck.find(card => card.id === id);
}

export function getRandomCard() {
  const randomIndex = Math.floor(Math.random() * fullDeck.length);
  const card = fullDeck[randomIndex];
  const isReversed = Math.random() < 0.3;
  return { ...card, isReversed };
}

export function drawCards(count) {
  const drawn = [];
  const usedIndices = new Set();
  
  while (drawn.length < count) {
    const randomIndex = Math.floor(Math.random() * fullDeck.length);
    if (!usedIndices.has(randomIndex)) {
      usedIndices.add(randomIndex);
      const card = fullDeck[randomIndex];
      const isReversed = Math.random() < 0.3;
      drawn.push({ ...card, isReversed });
    }
  }
  
  return drawn;
}
